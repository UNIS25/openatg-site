export type MessageKey = keyof typeof messages;
export function t(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
) {
  return messages[key][locale === "de" ? 0 : locale === "fr" ? 1 : 2].replace(
    /\{(\w+)\}/g,
    (match, name: string) => String(values[name] ?? match),
  );
}
export function stateName(locale: Locale, state: string) {
  return state in messages ? t(locale, state as MessageKey) : state;
}
